-- 课程造数汇总与反范式一致性核验
SELECT
  co.offering_id,
  co.term_id,
  c.course_name,
  co.capacity,
  co.enrolled_count AS denorm_enrolled_count,
  COALESCE(e_cnt.actual_cnt, 0) AS actual_enrolled_count,
  (co.enrolled_count = COALESCE(e_cnt.actual_cnt, 0)) AS is_consistent
FROM course_offering co
JOIN course c ON c.course_id = co.course_id
LEFT JOIN (
  SELECT offering_id, COUNT(*) AS actual_cnt
  FROM enrollment
  WHERE status = '已选'
  GROUP BY offering_id
) e_cnt ON e_cnt.offering_id = co.offering_id
ORDER BY co.offering_id;
